#!/usr/bin/env python3
"""由 prompts/ 下的提示词正文生成 GitHub Pages 页面。

用法：python3 tools/make_prompt_pages.py
产出：docs/prompts.html（中文）、docs/prompts.en.html（English）、docs/prompts/*.txt（原始文本）
"""
import os, html, shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "prompts")
DOCS = os.path.join(ROOT, "docs")
RAW = os.path.join(DOCS, "prompts")
os.makedirs(RAW, exist_ok=True)

FILES = [
    ("system-prompt.full.txt", "完整系统提示词 Full system prompt",
     "真实请求里发出去的 27,218 字符（3 个 block），逐字未改", "27,218 chars · 3 blocks · verbatim from a real request"),
    ("system-prompt.lean.txt", "精简版 Lean system prompt", "无头模式（claude -p）默认发出的版本", "the default for headless `claude -p`"),
    ("tool-descriptions.full.txt", "工具描述 Tool descriptions", "本次真实下发的 20 个工具的 description 字段", "20 tools, verbatim"),
    ("output-styles.txt", "输出风格 Output styles", "5 个内置风格的 prompt 与每轮提醒", "5 built-in styles"),
    ("sections-verbatim.md", "各节源码形态 Prompt sections (source form)",
     "从模块源码抽出的模板字面量，含 ${...} 占位符", "template literals as written in the source"),
]

for name, _, _, _ in FILES:
    shutil.copy(os.path.join(SRC, name), os.path.join(RAW, name))


def pre(path):
    text = open(path, encoding="utf-8").read()
    return f'<pre class="prompt">{html.escape(text)}</pre>'


def page(lang):
    zh = lang == "zh"
    title = "完整提示词" if zh else "Complete prompts"
    lede = ("这里是 Claude Code v2.1.287 的提示词正文，逐字未改。系统提示词来自一次**本地拦截的真实请求**"
            "（假密钥 + 本地 base URL，请求未离开本机），不是我的转述或重排。") if zh else \
           ("The prompt texts of Claude Code v2.1.287, verbatim. The system prompt comes from a **locally intercepted "
            "real request** (dummy key + a local base URL; no traffic left the machine) — not a paraphrase or a re-layout.")
    note = ("用途与边界：这些是分析取证的一部分，用于研究提示词工程。它们由 Anthropic 编写并随 CLI 分发，"
            "版权归 Anthropic 所有；本页只是把本机产物的内容如实展示出来。") if zh else \
           ("Scope: this material is part of the analysis, published to study prompt engineering. It was written by "
            "Anthropic and ships with the CLI; the copyright is theirs. This page merely shows what the local "
            "artifact contains.")
    other = "prompts.en.html" if zh else "prompts.html"
    other_label = "English" if zh else "中文"
    home = "index.html" if zh else "en.html"

    parts = [f"""<!DOCTYPE html>
<html lang="{'zh-CN' if zh else 'en'}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{title} · Claude Code v2.1.287</title>
<meta name="description" content="Verbatim prompt texts of Claude Code v2.1.287: full system prompt, lean variant, tool descriptions and output styles.">
<link rel="stylesheet" href="assets/style.css">
<style>
  pre.prompt{{background:var(--card);border:1px solid var(--line);border-radius:10px;padding:16px;
    font-size:12.5px;line-height:1.55;white-space:pre-wrap;word-break:break-word;max-height:75vh;overflow:auto}}
  .dl{{font-size:13px;margin:8px 0 18px}}
  .toc{{background:var(--card);border:1px solid var(--line);border-radius:12px;padding:14px 20px}}
  .toc ol{{margin:6px 0}}
</style>
</head>
<body>
<header class="top"><div class="inner">
  <span class="brand">Claude Code 逆向分析</span>
  <span class="spacer"></span>
  <nav>
    <a href="{home}">{'主页' if zh else 'Home'}</a>
    <a href="{other}">{other_label}</a>
    <a href="https://github.com/louisyeaaah/claude-code-re">GitHub ↗</a>
  </nav>
</div></header>
<div class="wrap" style="grid-template-columns:1fr;max-width:960px">
<main>
<h1>{title}</h1>
<p class="lede">{lede}</p>
<div class="card warn">{note}</div>
<div class="toc"><b>{'本页内容' if zh else 'On this page'}</b><ol>"""]
    for i, (name, zh_title, zh_sub, en_sub) in enumerate(FILES, 1):
        t = zh_title if zh else zh_title.split(" ", 1)[1] if " " in zh_title else zh_title
        sub = zh_sub if zh else en_sub
        parts.append(f'<li><a href="#f{i}">{t}</a> — {sub}</li>')
    parts.append("</ol></div>")

    for i, (name, zh_title, zh_sub, en_sub) in enumerate(FILES, 1):
        t = zh_title if zh else (zh_title.split(" ", 1)[1] if " " in zh_title else zh_title)
        sub = zh_sub if zh else en_sub
        label_dl = "下载原文" if zh else "Download"
        parts.append(f'\n<h2 id="f{i}">{t}</h2>\n<p class="meta">{sub}</p>\n'
                     f'<p class="dl"><a href="prompts/{name}">{label_dl} <code>{name}</code></a></p>\n'
                     + pre(os.path.join(RAW, name)))

    parts.append(f"""
<p style="margin-top:40px;color:var(--muted);font-size:13.5px">
{'这些文件的生成方式见 <code>tools/make_prompt_pages.py</code>；逐字取证的分析见' if zh else 'Generated by <code>tools/make_prompt_pages.py</code>; the analysis of this text is in'}
<a href="https://github.com/louisyeaaah/claude-code-re/tree/main/extracted">extracted/01-system-prompt{' .en' if not zh else ''}.md</a>。
</p>
</main></div>
<footer><p>{'本页展示的提示词由 Anthropic 编写，版权归其所有；此处仅作为本机产物的分析证据公开展示。' if zh else 'The prompts shown here were written by Anthropic and remain their copyright; they are reproduced as analysis evidence from a local artifact.'}</p></footer>
</body>
</html>
""")
    out = os.path.join(DOCS, "prompts.html" if zh else "prompts.en.html")
    open(out, "w", encoding="utf-8").write("".join(parts))
    print("wrote", out, os.path.getsize(out), "bytes")


page("zh")
page("en")
